#!/usr/bin/env node
/* Election candidate-effect descriptive audit. Never turn it into an unverified poll penalty. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const a=read('research/michigan-candidate-effect-audit-2026-11-02.json');
const sen=read('counties-watch/forecast-baselines.json').states.MI;
const governorArchive=read('research/governor-same-office-2014-2024.json');
assert.equal(a.pairs.length,9);
const differences=a.pairs.map(x=>{
 for(const race of [x.senate,x.governor])assert(Number.isFinite(race.dem)&&Number.isFinite(race.rep));
 for(const k of ['senateSource','governorSource'])assert(x[k].startsWith('https://'));
 const margin=+(x.governor.dem-x.governor.rep-x.senate.dem+x.senate.rep).toFixed(2);
 assert.equal(margin,x.governorMinusSenateMargin,'Paired survey mismatch '+x.id);
 return margin;
}).sort((x,y)=>x-y);
assert.equal(differences.filter(x=>x>0).length,8);
assert.equal(differences.filter(x=>x<0).length,1);
assert.equal(differences[4],2);
assert.equal(differences[0],-2);
assert.equal(differences.at(-1),9.9);
assert.equal(a.summary.meanGovernorMinusSenateMargin,2.83);
assert.equal(a.forecast.automaticAdditionalMuslimPenalty,0);
assert.equal(a.scientificValidation.status,'NOT VALIDATED');
assert.equal(a.scientificValidation.pairedPolling.n,9);
assert.equal(a.scientificValidation.pairedPolling.exactTwoSidedSignTestPAssumingIndependentPrespecifiedSamples,20/512);
assert(a.scientificValidation.primaryTransferValidation.includes('not calibrated'));
assert(a.scientificValidation.surveyModeValidation.includes('INSUFFICIENT'));

assert.equal(sen.adjustedMargin,-0.76,'Candidate context must alter the headline Ervin’s Take for Michigan');
const w=sen.candidateStrength;
assert.equal(w.pollingMarginD,10.2);assert.equal(w.actualMarginD,1);
assert.equal(w.overstatementD,w.pollingMarginD-w.actualMarginD);
assert.equal(w.retainedFraction,0.2);
assert.equal(w.adjustmentD,-1.84);
assert.equal(+(w.referenceMarginD+w.adjustmentD).toFixed(2),sen.adjustedMargin);
assert.equal(a.forecast.automaticAdditionalMuslimPenalty,0);
assert.equal(a.forecast.candidateStrength.adjustmentD,w.adjustmentD);
assert(a.forecast.candidateStrength.sourcePolling.startsWith('https://www.realclearpolling.com/'));
const homepage=fs.readFileSync('states/index.html','utf8');
assert(homepage.includes('../scripts/home-election-2026.js')&&!homepage.includes('window.ERVIN_DATA'),'State Desk must use standalone Senate forecasts and never embed legacy research UI');
const current=read('counties-watch/forecast-baselines.json').states.MI;
assert.equal(current.candidateStrength.adjustmentD,-1.84,'Michigan conditional forecast input should retain candidate audit evidence');
assert.equal(current.adjustedMargin,sen.adjustedMargin,'Public Senate control and Michigan State Desk must reuse one Ervin margin');
const science=read('research/michigan-candidate-sensitivity-2026-11-02.json');
assert(science.status.startsWith('NOT VALIDATED'));
assert.equal(science.primary.errorD,9.2);
assert.equal(science.comparison.errorD,6.4);
assert.equal(science.comparableHeldOutTests,0);
assert.equal(science.finalMarginD,sen.adjustedMargin);
assert(science.breakEvenWeight>.11&&science.breakEvenWeight<.12);
for(const x of science.sensitivity){
 assert.equal(x.rcp,+(1.08-9.2*x.weight).toFixed(2));
 assert.equal(x.alternative,+(1.08-6.4*x.weight).toFixed(2));
}
assert(science.sensitivity.find(x=>x.weight===.1).rcp>0);
assert(science.sensitivity.find(x=>x.weight===.2).rcp<0);
assert(fs.readFileSync('research/CANDIDATE_STRENGTH_VALIDATION_2026.md','utf8').includes('not robust'));
assert(fs.readFileSync('state/mi-candidate-audit.js','utf8').includes('Scientific status: NOT VALIDATED'));
assert.equal(sen.pollMargin,4.31);
assert(a.pairs.some(x=>x.mode.includes('Live operator')));
assert(a.pairs.some(x=>x.mode.includes('Online')));
assert(governorArchive.races.every(x=>x.year>=2018),'Independent governor 2014 cutoff changed');
const stateModule=fs.readFileSync('state/mi-candidate-audit.js','utf8');
const stateHtml=fs.readFileSync('state/index.html','utf8');
assert(stateModule.includes('miCandidateEffect')&&stateModule.includes('not applied')&&stateModule.includes('not evidence of a hidden voting preference'));
assert(/mi-candidate-audit\.js\?v=[^"']+/.test(stateHtml),'Michigan evidence versioned script must be loaded');
assert(stateHtml.includes('id="miCandidateEffectMount"'));
assert(stateModule.includes('|\\.\\.\\/')||stateModule.includes('|\\.\\.\\/'), 'Source link helper should permit relative audit JSON download');
assert(!fs.readFileSync('state/source-ledger.js','utf8').includes('candidateEffect'),'Optional audit must not break core bibliography fetches');
console.log('MI CANDIDATE-EFFECT AUDIT PASS',JSON.stringify({samples:a.pairs.length,widerGovernor:8,medianOfficeGap:2,range:[-2,9.9],candidateShift:-1.84,automaticReligionPenalty:0,ervinSenate:sen.adjustedMargin}));
