#!/usr/bin/env node
/* Snapshot-independent invariants for the published election-night office bars. */
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const read=x=>JSON.parse(fs.readFileSync(x,'utf8'));
const power=require('../election-night/power.js');
const g=require('./governor-backtest.js');
const senateModel=require('./statewide-ervin.js');
const inputG=read('governors/data.json'),history=read('research/governor-same-office-2014-2024.json');
const hs=read('house/ervin-forecast-2026-11-02.json');
const senate=read('counties-watch/forecast-baselines.json');
globalThis.ERVIN_GOVERNOR_BACKTEST=g;
const model=senateModel.apply(history,inputG,senate);
const out=power.compute(hs,model.senate,model.governor);
const sum=x=>x.D+x.R+x.T+(x.I||0)+(x.U||0);
assert.equal(sum(out.house),435);
assert.equal(sum(out.senate),100);
assert.equal(sum(out.governors),50);
assert.equal(out.house.T,hs.summary.ratings.Tossup,'Tossup districts cannot be counted as called seats');
assert.equal(out.house.U,hs.summary.redrawnUnrated,'Unknown redrawn districts must remain unassigned, not wins');
assert.equal(out.house.D+out.house.R+out.house.T+out.house.U,435,'House source ratings must cover exactly 435 districts');
assert.equal(hs.races['TX-09'].modelRating,'Likely R','Texas redraw cannot preserve the old Solid D numeric forecast');
assert.equal(hs.races['TX-09'].marginD,null,'No invented numeric Cook margin');
assert.equal(out.senate.D+out.senate.R+out.senate.I,100-out.senate.T,'Unassigned toss-up seats are neither Democratic nor Republican seats');
const senateTossups=model.senate.filter(x=>Math.abs(x.model?.adjustedMargin)<1.5).length;
assert.equal(out.senate.T,senateTossups,'Only current Senate estimates within ±1.5 points remain unassigned');
assert(out.senate.D>=0&&out.senate.R>=0,'Office bar cannot contain negative seat counts');
assert.equal(model.senate.length,17);
assert.equal(model.governor.length,36);
assert.equal(out.governors.offCycle,14);
const ohio=model.governor.find(x=>x.code==='OH');
assert(ohio&&Number.isFinite(ohio.model?.pollMargin),'Ohio governor requires an attributed published polling margin');
assert(Number.isFinite(ohio.model.adjustedMargin)||ohio.model.fallback,'Governor raw-poll fallback must be explicit');
const govTossups=model.governor.filter(x=>{
 const margin=Number.isFinite(x.model?.adjustedMargin)?x.model.adjustedMargin:x.model?.pollMargin;
 if(Number.isFinite(margin))return Math.abs(margin)<1.5;
 return !['Solid D','Likely D','Solid R','Likely R'].includes(x.qualitativeRating?.label);
}).length;
const sourceRated=model.governor.filter(x=>!Number.isFinite(x.model?.adjustedMargin)&&!Number.isFinite(x.model?.pollMargin)&&['Solid D','Likely D','Solid R','Likely R'].includes(x.qualitativeRating?.label)).length;
assert.equal(out.governors.T,govTossups,'Governor unresolved races must follow current 1.5-point/no-poll rule');
assert.equal(out.governors.rawOnly+out.governors.modeled+out.governors.sourceRated+out.governors.T,36,'Gov races must all be accounted for');
assert.equal(out.governors.sourceRated,sourceRated,'Qualitative governor ratings must be independently sourced, not numerically manufactured');
assert(model.governor.every(x=>x.model.events.every(e=>e.year>=2018&&e.year<2026)));
assert.throws(()=>power.compute({races:{}},model.senate,model.governor),/435/);
assert.throws(()=>power.compute(hs,[],model.governor),/17/);
assert.throws(()=>power.compute(hs,model.senate,[]),/36/);
const html=fs.readFileSync('states/index.html','utf8');
const root=fs.readFileSync('index.html','utf8');
const night=fs.readFileSync('election-night/night.js','utf8');
const nightHtml=fs.readFileSync('election-night/index.html','utf8');
const css=fs.readFileSync('scripts/home-power.css','utf8');
const browser=fs.readFileSync('scripts/home-power.js','utf8');
assert(html.includes('id="balanceOfPower"')&&html.includes('id="powerCards"')&&html.includes('id="nationMap"'));
assert(html.indexOf('id="watchSection"')<html.indexOf('id="balanceOfPower"'),'Public races-to-watch feature must appear before office-level seat totals');
assert(html.includes('scripts/home-election-2026.js')&&html.includes('scripts/home-control.js')&&html.includes('scripts/senate_control.js'),'Races to watch and public Senate-control sensitivity model must both be available');
assert(!html.includes('id="researchLab"')&&!html.includes('window.ERVIN_DATA'),'Retired research dashboard still exposed on the public homepage');
assert(html.includes('../election-night/power.js')&&html.includes('../scripts/home-power.js'),'State Desk balance module missing');
assert(root.includes('location.replace')&&root.includes('states/'),'Site root must send visitors to actual homepage');
assert(browser.includes('ERVIN_POWER.compute')&&browser.includes('ERVIN_POWER.render'));
assert(css.includes('power-segment-d')&&css.includes('power-segment-r')&&css.includes('power-segment-t'));
assert(!nightHtml.includes('id="balanceOfPower"')&&!nightHtml.includes('power.js'),'Election Night must not have forecast balance bars');
assert(!night.includes('ERVIN_POWER'),'Election Night must not run homepage balance calculations');
assert(!night.includes('2014–2024 same-state'),'2014 governor error cutoff regression');
console.log('HOMEPAGE POWER QA PASS',JSON.stringify({house:out.house,senate:out.senate,governors:out.governors}));
